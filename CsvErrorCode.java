/**
 * Коды ошибок загрузки CSV (уровень «максимум» лаб. 1).
 *
 * <p>Каждая пропущенная строка файла получает один код причины,
 * GUI показывает их в диалоге после загрузки.
 */
public enum CsvErrorCode {
    /** Неверное число колонок (ожидается 7 через ';'). */
    WRONG_FIELD_COUNT,
    /** Пустое обязательное поле «имя». */
    EMPTY_NAME,
    /** Пустое обязательное поле «телефон». */
    EMPTY_PHONE,
    /** Некорректный e-mail (нет '@'). */
    INVALID_EMAIL,
    /** Неизвестный тип записи (не contact/emergency/corporate). */
    UNKNOWN_TYPE,
    /** Корпоративный контакт не прошёл {@code validate()} (должность/номер). */
    INVALID_CORPORATE_FIELDS,
    /** Ошибка чтения файла (I/O). */
    IO_ERROR
}

import java.util.List;

/**
 * Контракт «сущность можно менять».
 *
 * <p>Решение: интерфейс <b>с методом</b>, а не маркер (обоснование для отчёта):
 * маркер ответил бы только на вопрос «можно ли показать кнопку "Изменить"»,
 * а {@code validate()} дополнительно даёт GUI список ошибок полей до сохранения
 * и позволяет заблокировать сохранение при некорректных данных.
 * Реализует его только редактируемый наследник с новыми полями
 * ({@code CorporateContact}); read-only тип ({@code EmergencyContact})
 * его не реализует, а базовый ({@code Contact}) — намеренно нет:
 * иначе подтип read-only унаследовал бы интерфейс автоматически
 * и проверка перестала бы его отличать. Кнопка «Изменить» блокируется
 * для read-only-типа; диалог для {@code corporate} валидируется через
 * {@code validate()}, для {@code contact} — через {@link ContactFactory}.
 */
public interface Editable {
    /** @return список ошибок; пустой список = данные корректны */
    List<String> validate();
}
